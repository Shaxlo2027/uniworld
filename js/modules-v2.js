let currentLanguage = "kaa";
const languageSelect = document.getElementById("languageSelect");

function applyLanguage(language) {
  currentLanguage = translations[language] ? language : "kaa";
  const dictionary = translations[currentLanguage];
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = dictionary[element.dataset.i18nPlaceholder];
    if (value !== undefined) element.setAttribute("placeholder", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAria];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const value = dictionary[element.dataset.i18nContent];
    if (value !== undefined) element.setAttribute("content", value);
  });

  if (languageSelect) languageSelect.value = currentLanguage;
  document.querySelectorAll("[data-year]").forEach((element) => {
    element.textContent = new Date().getFullYear();
  });

  try {
    localStorage.setItem("uniworld-language", currentLanguage);
  } catch (error) {
    // The page still works if browser storage is unavailable.
  }

  filterCampusCards();
}

if (languageSelect) {
  let savedLanguage = "kaa";
  try {
    savedLanguage = localStorage.getItem("uniworld-language") || "kaa";
  } catch (error) {
    savedLanguage = "kaa";
  }
  applyLanguage(savedLanguage);
  languageSelect.addEventListener("change", (event) => applyLanguage(event.target.value));
} else {
  applyLanguage("kaa");
}

const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");

function closeMenu() {
  if (!menuToggle || !mainNav) return;
  mainNav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}

if (menuToggle && mainNav) {
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.addEventListener("click", () => {
    const isOpen = mainNav.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
  });

  mainNav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeMenu);
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });
}

function filterCampusCards() {
  const searchInput = document.getElementById("campusSearch");
  const categorySelect = document.getElementById("campusType");
  const cards = document.querySelectorAll("[data-campus-card]");
  const noResults = document.getElementById("campusNoResults");

  if (!cards.length) return;

  const query = searchInput ? searchInput.value.trim().toLowerCase() : "";
  const category = categorySelect ? categorySelect.value : "all";
  let visibleCount = 0;

  cards.forEach((card) => {
    const matchesText = card.textContent.toLowerCase().includes(query);
    const matchesCategory = category === "all" || card.dataset.category === category;
    const visible = matchesText && matchesCategory;
    card.hidden = !visible;
    if (visible) visibleCount += 1;
  });

  if (noResults) noResults.hidden = visibleCount > 0;
}

const campusSearch = document.getElementById("campusSearch");
const campusType = document.getElementById("campusType");
if (campusSearch) campusSearch.addEventListener("input", filterCampusCards);
if (campusType) campusType.addEventListener("change", filterCampusCards);

const guideForm = document.getElementById("guideForm");
if (guideForm) {
  const question = document.getElementById("guideQuestion");
  const feedback = document.getElementById("guideFeedback");

  guideForm.addEventListener("submit", (event) => {
    event.preventDefault();
    if (!question.value.trim()) {
      feedback.textContent = translations[currentLanguage].guideRequired;
      question.setAttribute("aria-invalid", "true");
      question.focus();
      return;
    }

    question.removeAttribute("aria-invalid");
    feedback.textContent = translations[currentLanguage].guidePrepared;
  });

  question.addEventListener("input", () => question.removeAttribute("aria-invalid"));
}
